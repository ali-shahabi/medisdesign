/* Rebuilds content/journal.ts from data/posts.json.
   The four full articles are the only posts with real bodies on the site, so
   only those are exported as HTML; every other title stays an archive row. */
import fs from 'node:fs';

const POSTS = JSON.parse(fs.readFileSync('data/posts.json', 'utf8'));

const norm = (t) => (t || '').replace(/\u200c/g, '').replace(/\s+/g, ' ').trim();
const isoDay = (d) => new Date(d).toISOString().slice(0, 10);

const SLUGS = {
  'آکوستیک': 'acoustics',
  'عایق صوتی و نقش آن در صنعت ساختمان': 'sound-insulation',
  'پوشش های ضد حریق': 'fire-coating',
  'طراحی آکوستیک معماری': 'acoustic-architecture',
};

function postByTitle(title) {
  return POSTS.find((p) => norm((p.title || '').replace(/\u200c/g, '').trim()) === norm(title));
}

function bodyHtml(post) {
  const out = [];
  const walk = (blocks) => {
    for (const b of blocks || []) {
      if (b.type === 'richtext' || b.type === 'text') {
        const h = (b.html || '').trim();
        if (h) out.push(h);
      }
      if (b.blocks) walk(b.blocks);
      if (b.columns) b.columns.forEach((c) => walk(c.blocks));
    }
  };
  for (const s of post.sections || []) for (const r of s.rows || []) for (const c of r.columns || []) walk(c.blocks);
  let html = out.join('\n').replace(/@@IMG:[^\n]*/g, '').replace(/^زمان مطاله.*$/gm, '');
  html = html
    .replace(/<h1[^>]*>[\s\S]*?<\/h1>/g, '')
    .replace(/<p[^>]*>\s*زمان مطاله\s*:[\s\S]*?<\/p>/g, '')
    .replace(/\s*style="[^"]*"/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/<h3[^>]*>([\s\S]*?)<\/h3>/g, (m, inner) => (inner.replace(/<[^>]+>/g, '').trim().length > 110 ? `<p>${inner}</p>` : `<h3>${inner}</h3>`))
    .replace(/<h2[^>]*>([\s\S]*?)<\/h2>/g, (m, inner) => (inner.replace(/<[^>]+>/g, '').trim().length > 110 ? `<p>${inner}</p>` : `<h2>${inner}</h2>`))
    .replace(/<br\s*\/?>/g, '</p><p>')
    .replace(/<img[^>]*>/g, '')
    .replace(/<figure[^>]*>[\s\S]*?<\/figure>/g, '')
    .replace(/<p>\s*<\/p>/g, '');
  return html;
}

const skip = /^(آیکن|موسسه خیریه|بنیاد علوی|ساختمان مرکزی بیمه دی|سینمای داتین)/;
const seen = new Set();
const rows = [];
for (const p of POSTS) {
  const t = norm(p.title);
  if (!t || skip.test(t) || seen.has(t)) continue;
  seen.add(t);
  rows.push({ title: t, date: isoDay(p.date), ts: new Date(p.date).getTime() });
}
rows.sort((a, b) => b.ts - a.ts);
for (const r of rows) delete r.ts;

const bodies = {};
const dates = {};
for (const [title, slug] of Object.entries(SLUGS)) {
  const post = postByTitle(title);
  if (!post) {
    console.warn('!! missing post:', title);
    continue;
  }
  bodies[slug] = bodyHtml(post);
  dates[slug] = isoDay(post.date);
}

const file = `/* generated by scripts/build-content.mjs — do not edit by hand */
export type JournalRow = { title: string; date: string };

export const journal: JournalRow[] = ${JSON.stringify(rows, null, 2)};

export const articleDates: Record<string, string> = ${JSON.stringify(dates, null, 2)};

export const articleBodies: Record<string, string> = {
${Object.entries(bodies).map(([slug, html]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(html)},`).join('\n')}
};
`;

fs.writeFileSync('content/journal.ts', file);
console.log('rows', rows.length, 'bodies', Object.keys(bodies).length, (file.length / 1024).toFixed(1) + ' KB');
